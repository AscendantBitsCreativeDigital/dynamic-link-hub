	public static function get( $platform ) {
		$all = self::platforms();
		return isset( $all[ $platform ] ) ? $all[ $platform ] : $all['custom'];
	}

	public static function default_label( $platform ) {
		return self::get( $platform )['label'];
	}

	/**
	 * The background color for the icon circle: the platform's own
	 * official brand color when it has one, otherwise the hub's own
	 * button color (so email/phone/custom stay on-theme).
	 */
	public static function color( $platform, $fallback_hex ) {
		$data = self::get( $platform );
		if ( ! empty( $data['hex'] ) ) {
			return '#' . ltrim( $data['hex'], '#' );
		}
		return $fallback_hex;
	}

	/**
	 * The icon itself: the real brand mark when we have one, a plain
	 * text wordmark for LinkedIn, or a simple generic SVG otherwise.
	 * Every icon — including the LinkedIn wordmark — renders in the
	 * platform's own color on a transparent background; see the CSS in
	 * DLH_Shortcode::maybe_queue_styles().
	 */
	public static function markup( $platform ) {
		$data = self::get( $platform );

		if ( isset( $data['path'] ) ) {
			return '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="' . $data['path'] . '"/></svg>';
		}

		if ( isset( $data['svg'] ) ) {
			return self::svg( $data['svg'] );
		}

		return '<span class="dlh-social-glyph" aria-hidden="true">' . esc_html( $data['glyph'] ) . '</span>';
	}

